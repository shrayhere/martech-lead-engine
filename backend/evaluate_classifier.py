"""Measures AI classification accuracy on the held-out title set and writes docs/classification_evaluation.md.

    python evaluate_classifier.py                 # local scikit-learn model (free, no key)
    python evaluate_classifier.py --engine claude # Claude (needs ANTHROPIC_API_KEY; makes paid API calls)
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from app.services.classifier import (LABEL_DEFINITIONS, TARGETS, TEST_FILE, TRAIN_FILE,  # noqa: E402
                                     evaluate, label_counts, load_labeled)

DOC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "classification_evaluation.md")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", choices=["local", "claude"], default="local")
    ap.add_argument("--no-write", action="store_true")
    args = ap.parse_args()

    r = evaluate(args.engine)
    test_counts = label_counts(load_labeled(TEST_FILE))
    lines = [
        "# AI classification: accuracy on held-out job titles",
        "",
        f"Engine: **{r['engine']}**. Generated by `backend/evaluate_classifier.py`.",
        "",
        f"- Training titles: {r['train_titles']} (`backend/app/ml/title_labels_train.csv`)",
        f"- Test titles: {r['test_titles']} (`backend/app/ml/title_labels_test.csv`), none of which appear in the "
        f"training file after normalisation (overlap found: {len(r['titles_also_in_training'])})",
        "- Both files were labelled by hand for this project using the definitions below. They are a small, "
        "synthetic benchmark of title wording, not real CRM outcomes, so these numbers show the model follows the "
        "definitions on unseen titles; they do not prove the labels predict buying behaviour.",
        "",
        "| Label | Accuracy |",
        "|---|---:|",
    ]
    for t in TARGETS:
        lines.append(f"| {t} | {r['accuracy_pct'][t]}% |")
    lines += [f"| all three correct | {r['all_three_correct_pct']}% |", "", "## Errors", ""]
    if r["errors"]:
        lines += ["| Title | Label | Expected | Predicted |", "|---|---|---|---|"]
        for e in r["errors"]:
            for label, (exp, pred) in e["expected_vs_predicted"].items():
                lines.append(f"| {e['title']} | {label} | {exp} | {pred} |")
    else:
        lines.append("None.")
    lines += ["", "## Test-set label counts", ""]
    for t in TARGETS:
        lines.append(f"- {t}: " + ", ".join(f"{k} {v}" for k, v in sorted(test_counts[t].items())))
    lines += ["", "## Label definitions", "", "```", LABEL_DEFINITIONS.rstrip(), "```", ""]
    text = "\n".join(lines)
    print(text)
    if not args.no_write:
        with open(DOC, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"\nWritten to {os.path.normpath(DOC)}")


if __name__ == "__main__":
    main()
